print(1234)

# Aspas simples
print('Gilvam Júnior')
print(1, 'Gilvam "Júnior"')

# Aspas duplas
print("Júnior Oliveira")
print(2, "Júnior 'Oliveira'")

# Escape
print("Júnior \"Oliveira\"")

# r
